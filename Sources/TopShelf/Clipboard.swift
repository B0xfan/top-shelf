import AppKit
import CryptoKit
import Observation
import SwiftUI
import Vision

/// Clipboard history: text, rich text, pictures (their words found by on-device text recognition) and copied files.
/// Repeats are merged with a count; pinned clips stay; the rest go after a week. Passwords are never kept.
@Observable
final class ClipboardHistory {
    struct Clip: Codable, Identifiable, Equatable {
        enum Kind: String, Codable { case text, rich, image, files }
        var id = UUID()
        var kind: Kind
        var text: String           // the words searched and shown (file names for files, recognized text for pictures)
        var rtf: Data?
        var imageFile: String?     // picture stored as a PNG beside the history file
        var paths: [String]?
        var key: String            // fingerprint of the content, for merging repeats
        var count = 1
        var pinned = false
        var last: Date
    }

    static let keepFor: TimeInterval = 7 * 24 * 3600   // shortcut: fixed one week, make it a setting when a Settings window is designed
    static let maxClips = 200
    /// Pasteboard markers that password managers and similar apps set (nspasteboard.org).
    static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                            "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"]

    private(set) var clips: [Clip] = []
    var query = ""
    private let dir: URL?
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    init(dir: URL?, live: Bool) {
        self.dir = dir
        if let f = file, let data = try? Data(contentsOf: f) { clips = (try? JSONDecoder().decode([Clip].self, from: data)) ?? [] }
        prune()
        guard live else { return }
        // The Mac has no "clipboard changed" signal; a cheap counter check twice a second is the standard way.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll(.general) }
        timer?.tolerance = 0.25
    }

    private var file: URL? { dir?.appendingPathComponent("clipboard.json") }
    private func imageURL(_ name: String) -> URL? { dir?.appendingPathComponent("clipboard-images").appendingPathComponent(name) }

    func poll(_ pb: NSPasteboard) {
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if let c = read(pb) { add(c) }
    }

    /// The newest clip on a pasteboard, or nil for private or empty ones.
    func read(_ pb: NSPasteboard, now: Date = Date()) -> Clip? {
        let types = pb.types ?? []
        if types.contains(where: { Self.privateTypes.contains($0.rawValue) }) { return nil }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return Clip(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: ", "), paths: paths,
                        key: fingerprint(Data(paths.joined(separator: "\n").utf8)), last: now)
        }
        if let s = pb.string(forType: .string), !s.isEmpty {
            let rtf = pb.data(forType: .rtf)
            return Clip(kind: rtf == nil ? .text : .rich, text: s, rtf: rtf, key: fingerprint(Data(s.utf8)), last: now)
        }
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count < 20_000_000,
           let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
            let key = fingerprint(png)
            if !clips.contains(where: { $0.key == key }), let url = imageURL(key + ".png") {
                try? FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true,
                                                         attributes: [.posixPermissions: 0o700])
                try? png.write(to: url, options: .atomic)
                recognizeText(in: png, key: key)
            }
            return Clip(kind: .image, text: "", imageFile: key + ".png", key: key, last: now)
        }
        return nil
    }

    func add(_ c: Clip) {
        if let i = clips.firstIndex(where: { $0.key == c.key }) {
            var old = clips.remove(at: i)
            old.count += 1
            old.last = c.last
            clips.insert(old, at: 0)
        } else {
            clips.insert(c, at: 0)
        }
        prune(now: c.last)
    }

    /// Unpinned clips older than a week go, and only the newest 200 unpinned stay. Their pictures are deleted with them.
    func prune(now: Date = Date()) {
        var unpinned = 0
        let keep = clips.filter { c in
            if c.pinned { return true }
            unpinned += 1
            return unpinned <= Self.maxClips && now.timeIntervalSince(c.last) <= Self.keepFor
        }
        for gone in clips where !keep.contains(gone) {
            if let f = gone.imageFile, let url = imageURL(f) { try? FileManager.default.removeItem(at: url) }
        }
        clips = keep
        savePrivately(clips, to: file)
    }

    func togglePin(_ c: Clip) {
        guard let i = clips.firstIndex(of: c) else { return }
        clips[i].pinned.toggle()
        savePrivately(clips, to: file)
    }

    /// Puts a clip back on the clipboard (without counting it as a new copy).
    func copy(_ c: Clip, to pb: NSPasteboard = .general) {
        pb.clearContents()
        switch c.kind {
        case .text: pb.setString(c.text, forType: .string)
        case .rich:
            if let rtf = c.rtf { pb.setData(rtf, forType: .rtf) }
            pb.setString(c.text, forType: .string)
        case .image: if let img = image(c) { pb.writeObjects([img]) }
        case .files: pb.writeObjects((c.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        if pb == .general { lastChange = pb.changeCount }
    }

    func image(_ c: Clip) -> NSImage? { c.imageFile.flatMap(imageURL).flatMap { NSImage(contentsOf: $0) } }

    /// Pinned first, then newest; filtered by the search words.
    var visible: [Clip] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let hits = q.isEmpty ? clips : clips.filter { $0.text.localizedCaseInsensitiveContains(q) }
        return hits.filter(\.pinned) + hits.filter { !$0.pinned }
    }

    private func fingerprint(_ d: Data) -> String { SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined() }

    /// Finds the words in a copied picture on the Mac itself (Vision), so the picture can be searched.
    private func recognizeText(in png: Data, key: String) {
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let request = VNRecognizeTextRequest()
            try? VNImageRequestHandler(data: png).perform([request])
            let words = (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: " ")
            guard !words.isEmpty else { return }
            DispatchQueue.main.async {
                guard let self, let i = self.clips.firstIndex(where: { $0.key == key }) else { return }
                self.clips[i].text = words
                savePrivately(self.clips, to: self.file)
            }
        }
    }
}

struct ClipboardPage: View {
    let model: ShelfModel
    @FocusState private var searchFocused: Bool
    private let columns = Array(repeating: GridItem(.flexible(), spacing: 8), count: 4)

    var body: some View {
        @Bindable var history = model.clipboard
        VStack(spacing: 8) {
            TextField("Search clipboard", text: $history.query)
                .textFieldStyle(.plain).font(.system(size: 12))
                .padding(.horizontal, 10).padding(.vertical, 6)
                .background(Look.card, in: RoundedRectangle(cornerRadius: 10))
                .focused($searchFocused)
            if history.visible.isEmpty {
                Text(history.query.isEmpty ? "Things you copy show up here." : "Nothing matches.")
                    .font(Look.small).foregroundStyle(Look.dim).frame(maxWidth: .infinity, minHeight: 96)
            } else {
                ScrollView {
                    LazyVGrid(columns: columns, spacing: 8) {
                        ForEach(history.visible) { tile($0) }
                    }
                }
                .scrollIndicators(.never)
            }
        }
        .onAppear { searchFocused = !model.openedByHover }
    }

    private func tile(_ c: ClipboardHistory.Clip) -> some View {
        let history = model.clipboard
        return Button {
            history.copy(c)
            model.close()
        } label: {
            ZStack(alignment: .bottomTrailing) {
                Group {
                    if c.kind == .image, let img = history.image(c) {
                        Image(nsImage: img).resizable().aspectRatio(contentMode: .fill)
                    } else {
                        Text(c.kind == .files ? "Files: " + c.text : c.text)
                            .font(Look.small).padding(8)
                            .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                    }
                }
                .frame(maxWidth: .infinity).frame(height: 96).clipped()
                Text(c.pinned ? "pinned" : c.count > 1 ? "x\(c.count)" : c.kind == .image ? "image" : "")
                    .font(.system(size: 10)).foregroundStyle(Look.dim).padding(.trailing, 6).padding(.bottom, 4)
            }
            .background(Look.card)
            .clipShape(RoundedRectangle(cornerRadius: 10))
            .overlay(RoundedRectangle(cornerRadius: 10).strokeBorder(c.pinned ? Look.orange : .clear, lineWidth: 1.5))
            .contentShape(RoundedRectangle(cornerRadius: 10))
        }
        .buttonStyle(.plain)
        .contextMenu { Button(c.pinned ? "Unpin" : "Pin") { history.togglePin(c) } }
        .help("Click to copy")
        .accessibilityLabel((c.pinned ? "Pinned: " : "") + (c.text.isEmpty ? "Picture" : c.text))
        .accessibilityHint("Copies it back to the clipboard")
    }
}
